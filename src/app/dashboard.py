"""
Streamlit dashboard for Pitchline.

Shows upcoming fixture predictions with AI-generated previews, and tracks
live model accuracy against real tournament results as they come in.

Run with: streamlit run src/app/dashboard.py
"""

import streamlit as st
import pandas as pd
import plotly.express as px
from pathlib import Path
import sys

sys.path.append(str(Path(__file__).resolve().parents[2]))

from src.models.track_accuracy import get_live_accuracy

PROCESSED_DIR = Path(__file__).resolve().parents[2] / "data" / "processed"

st.set_page_config(page_title="Pitchline", layout="wide", page_icon="⚽")

st.title("⚽ Pitchline")
st.caption(
    "Real World Cup predictions, real data — predictions generated by an XGBoost model "
    "trained on ELO ratings, recent form, and 36 years of historical head-to-head data, "
    "validated live against the actual tournament."
)
st.info(
    "📋 More views in the sidebar: **Match at a Glance** · **Upset Detector** · "
    "**Tournament Forecast** · **Data Quality** · **Experiments**"
)

predictions_path = PROCESSED_DIR / "fixture_predictions.csv"

if not predictions_path.exists():
    st.warning(
        "No predictions found yet. Run `python -m src.models.predict --fixtures "
        "data/processed/upcoming_fixtures.csv` first."
    )
    st.stop()

predictions = pd.read_csv(predictions_path)

col1, col2, col3 = st.columns(3)

live_stats = get_live_accuracy()
with col1:
    st.metric("Matches Predicted", len(predictions))
with col2:
    if live_stats["matches_scored"] > 0:
        st.metric("Live Accuracy", f"{live_stats['accuracy']:.1%}")
    else:
        st.metric("Live Accuracy", "No results yet")
with col3:
    st.metric("Matches Scored So Far", live_stats["matches_scored"])

st.divider()

st.subheader("Upcoming Fixture Predictions")

for _, match in predictions.iterrows():
    with st.container(border=True):
        c1, c2, c3 = st.columns([2, 3, 2])

        with c1:
            st.markdown(f"### {match['home_team']} vs {match['away_team']}")
            st.caption(pd.to_datetime(match["date"]).strftime("%B %d, %Y"))

        with c2:
            prob_df = pd.DataFrame({
                "Outcome": [f"{match['home_team']} Win", "Draw", f"{match['away_team']} Win"],
                "Probability": [match["prob_home_win"], match["prob_draw"], match["prob_away_win"]],
            })
            fig = px.bar(
                prob_df, x="Probability", y="Outcome", orientation="h",
                range_x=[0, 1], height=140,
            )
            fig.update_layout(margin=dict(l=0, r=0, t=10, b=10), showlegend=False)
            st.plotly_chart(fig, use_container_width=True, key=f"chart_{match['home_team']}_{match['away_team']}")

        with c3:
            st.markdown("**AI Scouting Report**")
            preview = match.get("ai_preview", "Preview not generated for this match.")
            st.write(preview)

st.divider()

if live_stats["matches_scored"] > 0:
    st.subheader("Live Tournament Accuracy")
    log = pd.read_csv(PROCESSED_DIR / "live_results_log.csv")
    log["cumulative_accuracy"] = log["correct"].expanding().mean()

    fig = px.line(
        log, x=log.index + 1, y="cumulative_accuracy",
        labels={"x": "Match Number", "cumulative_accuracy": "Cumulative Accuracy"},
        title="Model Accuracy as the Tournament Progresses",
    )
    fig.update_yaxes(range=[0, 1], tickformat=".0%")
    st.plotly_chart(fig, use_container_width=True)

    st.dataframe(
        log[["home_team", "away_team", "home_score", "away_score", "correct"]],
        use_container_width=True,
    )
else:
    st.info("Live accuracy will populate here once real match results are logged via `track_accuracy.log_actual_result()`.")
